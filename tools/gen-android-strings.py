#!/usr/bin/env python3
"""Generates Android's strings from the iPhone's L10n files, so both apps say the same thing.

Every `LocalizedStringResource("area.key", defaultValue: "…")` and `String(localized: "area.key",
defaultValue: "…")` in iosApp/Mode/Resources/L10n*.swift becomes `<string name="area_key">` in
app/android/src/main/res/values/strings_mode.xml. `\\(value)` placeholders become %1$s, %2$s….
Words that name iPhone things are swapped for Android's (WORDS), and a few strings that say something
different on Android are written out in OVERRIDES. Android-only strings live in strings.xml by hand.

Run from the repo root: python3 tools/gen-android-strings.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = sorted(glob.glob(os.path.join(ROOT, "iosApp/Mode/Resources/L10n*.swift")))
OUT = os.path.join(ROOT, "app/android/src/main/res/values/strings_mode.xml")

# Applied in order to every string; specific phrases first.
WORDS = [
    ("Sign-ins stay in this iPhone's Keychain.", "Sign-ins stay encrypted on this phone."),
    ("this iPhone's Keychain", "this phone's secure storage"),
    ("this iPhone’s Keychain", "this phone’s secure storage"),
    ("the Keychain", "secure storage"),
    ("Keychain", "secure storage"),
    ("“Hey Siri, start Mode”", "Hold the power button"),
    ("Hey Siri, start Mode", "Hold the power button"),
    ("Hey Siri", "Hold power"),
    ("Siri", "the assistant"),
    ("Dynamic Island", "notification"),
    ("Lock Screen", "lock screen"),
    ("Home Screen", "home screen"),
    ("Control Center", "Quick Settings"),
    ("Face ID", "your fingerprint"),
    ("Files app", "Files"),
    ("iCloud Drive", "Google Drive"),
    ("AirDrop", "Quick Share"),
    ("iOS", "Android"),
    ("On iPhone", "On this phone"),
    ("on iPhone", "on this phone"),
    ("iPhone", "phone"),
    ("Apple", "Android"),
]

# Strings that say something different on Android (key → text).
OVERRIDES = {
    "firstRun.permissionsNote": "Mo opens the app and does it while you watch. You can stop it any time from the notification.",
    "firstRun.widgetHow": "Touch and hold your home screen, tap Widgets, and pick Mode.",
}


def android_name(key):
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", key).replace(".", "_").replace("-", "_").lower()
    return re.sub(r"_+", "_", snake)


def swift_unescape(value):
    return value.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def to_android(value):
    """A Swift default value → (Android string text, formatted)."""
    parts = re.split(r"\\\(([^()]*(?:\([^()]*\)[^()]*)*)\)", value)
    text = ""
    n = 0
    # The same value used twice ("at \(time) … at \(time)") keeps one number.
    numbers = {}
    for i, part in enumerate(parts):
        if i % 2 == 0:
            text += swift_unescape(part).replace("%", "%%")
        else:
            if part not in numbers:
                n += 1
                numbers[part] = n
            text += f"%{numbers[part]}$s"
    if n == 0:
        text = text.replace("%%", "%")
    for old, new in WORDS:
        text = text.replace(old, new)
    escaped = (
        text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    )
    if escaped.startswith("@") or escaped.startswith("?"):
        escaped = "\\" + escaped
    return escaped, n > 0


def main():
    pattern = re.compile(r'(?:LocalizedStringResource\(|String\(localized:\s*)"([^"]+)",\s*defaultValue:\s*"((?:[^"\\]|\\.)*)"')
    seen = {}
    for path in SOURCES:
        for key, value in pattern.findall(open(path).read()):
            if key in seen:
                continue
            seen[key] = OVERRIDES.get(key, None) or value
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- Generated by tools/gen-android-strings.py from iosApp/Mode/Resources/L10n*.swift. Do not edit. -->\n",
        "<resources>\n",
    ]
    names = set()
    for key in sorted(seen):
        name = android_name(key)
        if name in names:
            raise SystemExit(f"two keys make {name}")
        names.add(name)
        if key in OVERRIDES:
            text, formatted = to_android(OVERRIDES[key])
        else:
            text, formatted = to_android(seen[key])
        plain = "%" in text and not formatted
        lines.append(f'    <string name="{name}"{" formatted=\"false\"" if plain else ""}>{text}</string>\n')
    lines.append("</resources>\n")
    open(OUT, "w").write("".join(lines))
    print(f"{len(seen)} strings")


if __name__ == "__main__":
    main()
