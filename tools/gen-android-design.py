def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def colors():
    folder = os.path.join(IOS, "Resources/Colors.xcassets")
    rows = []
    for entry in sorted(os.listdir(folder)):
        if not entry.endswith(".colorset"):
            continue
        name = entry[: -len(".colorset")]
        data = json.load(open(os.path.join(folder, entry, "Contents.json")))
        light = dark = None
        for c in data["colors"]:
            comps = c["color"]["components"]
            value = tuple(float(comps[k]) for k in ("red", "green", "blue", "alpha"))
            if any(a.get("value") == "dark" for a in c.get("appearances", [])):
                dark = value
            else:
                light = value
        rows.append((name, light, dark or light))

    def argb(v):
        r, g, b, a = (max(0, min(255, round(x * 255))) for x in v)
        return f"Color(0x{a:02X}{r:02X}{g:02X}{b:02X})"

    out = [HEADER, "package com.piyush.mode.design\n\n", "import androidx.compose.ui.graphics.Color\n\n"]
    out.append("/** Mode's named colours, one per colourset of the iPhone's Colors.xcassets. */\n")
    out.append("public class ModeColorTokens(\n")
    for name, _, _ in rows:
        out.append(f"    public val {name[0].lower() + name[1:]}: Color,\n")
    out.append(") {\n")
    out.append("    /** Every colour by name, for the catalogue. */\n")
    out.append("    public fun all(): List<Pair<String, Color>> = listOf(\n")
    for name, _, _ in rows:
        n = name[0].lower() + name[1:]
        out.append(f'        "{n}" to {n},\n')
    out.append("    )\n\n")
    out.append("    public companion object {\n")
    for mode, idx in (("Light", 1), ("Dark", 2)):
        out.append(f"        public val {mode}: ModeColorTokens = ModeColorTokens(\n")
        for row in rows:
            out.append(f"            {row[0][0].lower() + row[0][1:]} = {argb(row[idx])},\n")
        out.append("        )\n")
    out.append("    }\n}\n")
    os.makedirs(KOTLIN, exist_ok=True)
    open(os.path.join(KOTLIN, "ModeColorTokens.kt"), "w").write("".join(out))
    return len(rows)


def vector(paths, viewbox, name, fill="#FF000000"):
    """paths: [(d, evenodd)]; viewbox: (minx, miny, w, h)."""
    minx, miny, w, h = viewbox
    body = "".join(
        f'        <path android:fillColor="{fill}"{" android:fillType=\"evenOdd\"" if evenodd else ""}\n'
        f'            android:pathData="{d}" />\n'
        for d, evenodd in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {name}. Generated by tools/gen-android-design.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        f'    android:viewportWidth="{w:g}" android:viewportHeight="{h:g}">\n'
        f'    <group android:translateX="{-minx:g}" android:translateY="{-miny:g}">\n'
        f"{body}"
        "    </group>\n"
        "</vector>\n"
    )


NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def normalize_path(d):
    """Spells out SVG path data so Android's parser reads it as browsers do.

    SVG lets an arc's two flags be packed with what follows ("a5 5 0 110 10" is flags 1, 1 and
    x 0); Android reads "110" as one number. Every command's numbers are written out in full.
    """
    out = []
    i = 0
    cmd = None
    counts = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
    while i < len(d):
        ch = d[i]
        if ch.isalpha():
            cmd = ch
            out.append(ch)
            i += 1
            if cmd in "zZ":
                continue
            continue
        if ch in " ,\t\n":
            i += 1
            continue
        n = counts[cmd.lower()]
        args = []
        for k in range(n):
            while i < len(d) and d[i] in " ,\t\n":
                i += 1
            if cmd.lower() == "a" and k in (3, 4):  # a flag: one character, 0 or 1
                args.append(d[i])
                i += 1
            else:
                m = NUMBER.match(d, i)
                args.append(m.group(0))
                i = m.end()
        out.append(" ".join(args) + " ")
    return "".join(out).strip()


def parse_svg(text):
    vb = re.search(r'viewBox="([^"]+)"', text)
    if vb:
        viewbox = tuple(float(x) for x in vb.group(1).split())
    else:  # A few older icons give only a width and height.
        w = float(re.search(r'width="([\d.]+)"', text).group(1))
        h = float(re.search(r'height="([\d.]+)"', text).group(1))
        viewbox = (0.0, 0.0, w, h)
    root = re.search(r"<svg\b([^>]*)>", text).group(1)
    root_evenodd = 'fill-rule="evenodd"' in root
    paths = []
    for m in re.finditer(r"<path\b([^>]*)/?>", text):
        attrs = m.group(1)
        d = normalize_path(re.search(r'\sd="([^"]+)"', attrs).group(1))
        rule = re.search(r'fill-rule="(\w+)"', attrs)
        paths.append((d, rule.group(1) == "evenodd" if rule else root_evenodd))
    if not paths:
        raise ValueError("no paths")
    return paths, viewbox


def logos():
    folder = os.path.join(IOS, "Resources/Logos.xcassets")
    drawable = os.path.join(RES, "drawable")
    os.makedirs(drawable, exist_ok=True)
    names = []
    for entry in sorted(os.listdir(folder)):
        if not entry.endswith(".imageset"):
            continue
        svg = [f for f in os.listdir(os.path.join(folder, entry)) if f.endswith(".svg")][0]
        paths, viewbox = parse_svg(open(os.path.join(folder, entry, svg)).read())
        name = entry[: -len(".imageset")].replace("-", "_")
        open(os.path.join(drawable, f"{name}.xml"), "w").write(vector(paths, viewbox, entry[: -len('.imageset')]))
        names.append(name)
    # Android only: the phone's own voice and listening, from Simple Icons (CC0).
    for name, url in ANDROID_LOGOS.items():
        cached = os.path.join(CACHE, f"logo_{name}.svg")
        if not os.path.exists(cached):
            os.makedirs(CACHE, exist_ok=True)
            with urllib.request.urlopen(url) as r:
                open(cached, "wb").write(r.read())
        paths, viewbox = parse_svg(open(cached).read())
        open(os.path.join(drawable, f"logo_{name}.xml"), "w").write(vector(paths, viewbox, f"Simple Icons: {name}"))
        names.append(f"logo_{name}")
    return names


def icons():
    os.makedirs(CACHE, exist_ok=True)
    drawable = os.path.join(RES, "drawable")
    os.makedirs(drawable, exist_ok=True)
    swift = open(os.path.join(IOS, "Tokens/ModeIcon.swift")).read()
    cases = re.findall(r"case (\w+) = \"", swift)
    missing = [c for c in cases if c not in ICONS]
    ICONS.update(ANDROID_ICONS)
    cases += list(ANDROID_ICONS)
    if missing:
        sys.exit(f"ModeIcon cases with no Android icon: {missing}")
    for case in cases:
        symbol, filled = ICONS[case]
        file = f"{symbol}_fill1_24px.svg" if filled else f"{symbol}_24px.svg"
        cached = os.path.join(CACHE, file)
        if not os.path.exists(cached):
            url = f"https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{symbol}/materialsymbolsrounded/{file}"
            with urllib.request.urlopen(url) as r:
                open(cached, "wb").write(r.read())
        paths, viewbox = parse_svg(open(cached).read())
        out = f"ic_mode_{snake(case)}.xml"
        open(os.path.join(drawable, out), "w").write(vector(paths, viewbox, f"Material Symbols Rounded: {symbol}{' (filled)' if filled else ''}"))
    # The enum the screens use.
    lines = [HEADER, "package com.piyush.mode.design\n\n", "import androidx.annotation.DrawableRes\n\n"]
    lines.append("/** Every icon Mode shows (the same cases as the iPhone's ModeIcon), as Material Symbols. */\n")
    lines.append("public enum class ModeIcon(@DrawableRes public val res: Int) {\n")
    for case in cases:
        lines.append(f"    {case[0].upper() + case[1:]}(R.drawable.ic_mode_{snake(case)}),\n")
    lines.append("}\n")
    open(os.path.join(KOTLIN, "ModeIcon.kt"), "w").write("".join(lines))
    return len(cases)


def main():
    n_colors = colors()
    n_logos = len(logos())
    n_icons = icons()
    print(f"{n_colors} colours, {n_logos} logos, {n_icons} icons")


if __name__ == "__main__":
    main()
